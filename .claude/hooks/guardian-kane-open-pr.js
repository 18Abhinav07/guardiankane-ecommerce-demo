import { existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { readTracker, findTask } from '../../lib/tracker.js';

const TRACKER_PATH = '.testmuai/task-tracker.md';

// Composes a PR body from the task's own recorded evidence — never
// hand-written prose — so a PR always cites the same verification the Stop
// hook actually ran, not a claim about it.
export function buildPrBody(task) {
  const lines = [`## ${task.title}`];
  if (task.prd_ref) {
    lines.push('', `**PRD reference:** ${task.prd_ref}`);
  }
  if (task.test_file) {
    const files = Array.isArray(task.test_file) ? task.test_file : [task.test_file];
    if (files.length > 0) lines.push('', `**Verified by:** ${files.join(', ')}`);
  }
  const verdict = task.last_verdict;
  if (verdict) {
    lines.push('', '**Last verification:**');
    if (verdict.summary) lines.push(`- ${verdict.summary}`);
    if (verdict.test_url) lines.push(`- Evidence: ${verdict.test_url}`);
  }
  lines.push('', '_Generated by GuardianKane — verified via kane-cli, not self-reported._');
  return lines.join('\n');
}

export function hasUncommittedChanges(files) {
  if (!Array.isArray(files) || files.length === 0) return false;
  // execFileSync passes argv directly to git, not through a shell — a file
  // path containing quotes/backticks/$() can't break out of interpolation
  // the way it could with execSync's shell-string form.
  const output = execFileSync('git', ['status', '--porcelain', '--', ...files], { encoding: 'utf8' });
  return output.trim() !== '';
}

function runCli(taskId) {
  if (!taskId) {
    console.error('usage: node guardian-kane-open-pr.js <task-id>');
    process.exitCode = 1;
    return;
  }
  if (!existsSync(TRACKER_PATH)) {
    console.error(`no task tracker found at ${TRACKER_PATH} — has /guardian-kane start been run in this project?`);
    process.exitCode = 1;
    return;
  }
  const { tasks } = readTracker(TRACKER_PATH);
  const task = findTask(tasks, taskId);
  if (!task) {
    console.error(`${taskId} not found in ${TRACKER_PATH}.`);
    process.exitCode = 1;
    return;
  }
  if (task.state !== 'KANE_VERIFIED') {
    console.error(`${task.id} is not yet KANE_VERIFIED, cannot open a PR for it.`);
    process.exitCode = 1;
    return;
  }
  if (hasUncommittedChanges(task.files)) {
    console.error(`${task.id} has uncommitted changes in its files — commit first.`);
    process.exitCode = 1;
    return;
  }
  process.stdout.write(buildPrBody(task));
}

if (import.meta.url === `file://${process.argv[1]}`) {
  runCli(process.argv[2]);
}
